#!/usr/bin/env bash
# Generates the compose file from config and wraps `docker compose`.

compose() {
  docker compose -p "$DEVBOX_NAME" -f "$DEVBOX_COMPOSE_FILE" "$@"
}

ensure_running() {
  [[ -f "$DEVBOX_COMPOSE_FILE" ]] || die "$DEVBOX_NAME has not been started (devbox up)"
  local id
  id="$(compose ps -q "$DEVBOX_SERVICE" 2>/dev/null || true)"
  [[ -n "$id" ]] || die "$DEVBOX_NAME is not running (devbox up)"
}

# Emits YAML on stdout. Named volumes keep dependency caches (node_modules, ~/.m2, pip) off the
# bind mount, which is both faster on macOS/Windows and avoids host/container binary mismatches.
render_compose() {
  local host_port="${DEVBOX_HOST_PORT:-$DEVBOX_PORT}"
  local depends=() envs=()
  [[ "$WITH_POSTGRES" == "true" ]] && depends+=("postgres") && envs+=("DATABASE_URL=postgres://dev:dev@postgres:5432/dev")
  [[ "$WITH_MYSQL" == "true" ]] && depends+=("mysql") && envs+=("MYSQL_URL=mysql://dev:dev@mysql:3306/dev")
  [[ "$WITH_REDIS" == "true" ]] && depends+=("redis") && envs+=("REDIS_URL=redis://redis:6379")
  local e command volumes=()
  for e in ${EXTRA_ENV:-}; do envs+=("$e"); done
  if [[ -n "${START_CMD:-}" ]]; then
    command="[\"sh\", \"-lc\", \"${START_CMD//\"/\\\"}\"]"
  else
    command='["sleep", "infinity"]'
  fi

  cat <<YAML
# Generated by devbox from .devbox. Do not edit; changes are overwritten on 'devbox up'.
services:
  $DEVBOX_SERVICE:
    build:
      context: .
      dockerfile: Dockerfile.dev
    working_dir: $DEVBOX_WORKDIR
    command: $command
    ports:
      - "$host_port:$DEVBOX_CONTAINER_PORT"
    volumes:
      - .:$DEVBOX_WORKDIR
YAML
  local dir i=0
  for dir in ${CACHE_DIRS:-}; do
    printf '      - cache%d:%s\n' "$i" "$dir"
    i=$((i + 1))
  done
  if ((${#envs[@]})); then
    echo "    environment:"
    for e in "${envs[@]}"; do printf '      - %s\n' "$e"; done
  fi
  if ((${#depends[@]})); then
    echo "    depends_on:"
    for d in "${depends[@]}"; do printf '      %s:\n        condition: service_healthy\n' "$d"; done
  fi
  [[ "$WITH_POSTGRES" == "true" ]] && cat <<YAML
  postgres:
    image: postgres:$POSTGRES_VERSION
    environment: { POSTGRES_USER: dev, POSTGRES_PASSWORD: dev, POSTGRES_DB: dev }
    volumes: [pgdata:/var/lib/postgresql/data]
    healthcheck: { test: ["CMD-SHELL", "pg_isready -U dev"], interval: 2s, retries: 30 }
YAML
  [[ "$WITH_MYSQL" == "true" ]] && cat <<YAML
  mysql:
    image: mysql:$MYSQL_VERSION
    environment: { MYSQL_USER: dev, MYSQL_PASSWORD: dev, MYSQL_DATABASE: dev, MYSQL_ROOT_PASSWORD: dev }
    volumes: [mysqldata:/var/lib/mysql]
    healthcheck: { test: ["CMD", "mysqladmin", "ping", "-h", "localhost", "-pdev"], interval: 3s, retries: 30 }
YAML
  [[ "$WITH_REDIS" == "true" ]] && cat <<YAML
  redis:
    image: redis:$REDIS_VERSION-alpine
    healthcheck: { test: ["CMD", "redis-cli", "ping"], interval: 2s, retries: 30 }
YAML
  echo "volumes:"
  [[ "$WITH_POSTGRES" == "true" ]] && echo "  pgdata:"
  [[ "$WITH_MYSQL" == "true" ]] && echo "  mysqldata:"
  i=0
  for dir in ${CACHE_DIRS:-}; do
    printf '  cache%d:\n' "$i"
    i=$((i + 1))
  done
  echo "  _devbox_placeholder:"
}
